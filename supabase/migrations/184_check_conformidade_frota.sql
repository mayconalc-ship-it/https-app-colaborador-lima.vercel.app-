-- Pedido do dono (25/11/2026): a planilha "CheckList Conformidade
-- Caminhoes - 2026" (\\192.168.4.250\Frota\DPO ... \BARREIRAS) vira um
-- modulo do app. O check e BIMESTRAL (jan-fev, mar-abr ... nov-dez),
-- feito e ASSINADO por alguem da frota (pessoa liberada no modulo
-- "frota-check"), com FOTO obrigatoria em todo item NOK. O Gestor LOG le
-- o farol de quem esta pendente (aba Frota > Check bimestral).
--
-- O que veio da planilha (conferido em 25/11):
--   - 49 itens em 6 grupos (Cabine 15, Frontal 8, Bau 14, Traseira 9,
--     Pneus 1, Itens extras 2), com classificacao e gravidade;
--   - o manual "Especificacoes Caminhoes": 96 defeitos descritos, cada um
--     com a sua gravidade (leve, medio, grave, bloqueio imediato). No app,
--     o NOK pede QUAL defeito -- e a gravidade sai dele, sem chute.
--     Ficaram fora (estao no manual, mas nao na planilha): "Adesivos e
--     identificacoes de transito" (frontal), "Cofre" e "Kit higienizacao".
--     O defeito "Milimetragem" do pneu entra no item Pneus (a planilha
--     tem uma coluna so de pneus);
--   - aba "Divisao placas": 38 caminhoes + 4 empilhadeiras com o dono de
--     cada placa (Gustavo, Gabriel, Johnatan). Empilhadeiras ficam fora:
--     o checklist e de caminhao;
--   - historico 2026 mensal (jan-nov, sem outubro): entra um por bimestre
--     (o mes mais novo), como "planilha" -- sem foto e sem assinatura.
--     6 placas que sairam da frota entram desativadas, so pelo historico.

-- ------------------------------------------------------------------
-- 1) TABELAS
-- ------------------------------------------------------------------
create table if not exists public.cf_itens (
  id uuid primary key default gen_random_uuid(),
  ordem smallint not null unique,
  grupo text not null,
  nome text not null,
  classificacao text not null,
  -- o texto da linha 4 da planilha (ex.: LEVE/BLOQUEIO IMEDIATO): referencia
  gravidade_planilha text,
  ativo boolean not null default true
);

create table if not exists public.cf_defeitos (
  id uuid primary key default gen_random_uuid(),
  item_id uuid not null references public.cf_itens(id) on delete cascade,
  ordem smallint not null,
  descricao text not null,
  classificacao text,
  gravidade text not null check (gravidade in ('leve', 'medio', 'grave', 'bloqueio')),
  constraint cf_defeitos_ordem_unica unique (item_id, ordem)
);

create table if not exists public.cf_veiculos (
  id uuid primary key default gen_random_uuid(),
  revenda_id uuid not null references public.revendas(id) on delete cascade,
  placa text not null check (placa ~ '^[A-Z0-9]{6,8}$'),
  descricao text check (descricao is null or char_length(descricao) <= 80),
  -- quem responde pela placa (cadastro do app); o nome da planilha fica
  -- ate a lideranca escolher a pessoa
  responsavel_id uuid references public.profiles(id) on delete set null,
  responsavel_nome text,
  ativo boolean not null default true,
  criado_em timestamptz not null default now(),
  constraint cf_veiculos_placa_unica unique (revenda_id, placa)
);

create table if not exists public.cf_checks (
  id uuid primary key default gen_random_uuid(),
  revenda_id uuid not null references public.revendas(id) on delete cascade,
  veiculo_id uuid not null references public.cf_veiculos(id) on delete restrict,
  ano smallint not null,
  bimestre smallint not null check (bimestre between 1 and 6),
  origem text not null default 'app' check (origem in ('app', 'planilha')),
  mes_planilha smallint,
  -- planilha = veio do historico (conta como feito, sem assinatura)
  status text not null default 'em_andamento' check (status in ('em_andamento', 'assinado', 'planilha')),
  iniciado_por uuid references public.profiles(id) on delete set null,
  iniciado_por_nome text,
  iniciado_em timestamptz not null default now(),
  km integer check (km is null or km between 0 and 5000000),
  assinado_por uuid references public.profiles(id) on delete set null,
  assinado_por_nome text,
  assinado_cargo text,
  assinado_em timestamptz,
  assinatura_caminho text,
  total smallint,
  ok smallint,
  nok smallint,
  conformidade numeric(5,4),
  pior_gravidade text,
  observacao text check (observacao is null or char_length(observacao) <= 1000),
  atualizado_em timestamptz not null default now(),
  constraint cf_checks_bimestre_unico unique (veiculo_id, ano, bimestre)
);

create index if not exists cf_checks_revenda_idx on public.cf_checks (revenda_id, ano, bimestre);

create table if not exists public.cf_respostas (
  id uuid primary key default gen_random_uuid(),
  check_id uuid not null references public.cf_checks(id) on delete cascade,
  item_id uuid not null references public.cf_itens(id) on delete restrict,
  revenda_id uuid not null references public.revendas(id) on delete cascade,
  ok boolean not null,
  defeito_id uuid references public.cf_defeitos(id) on delete set null,
  gravidade text check (gravidade is null or gravidade in ('leve', 'medio', 'grave', 'bloqueio')),
  observacao text check (observacao is null or char_length(observacao) <= 500),
  respondido_por uuid references public.profiles(id) on delete set null,
  respondido_por_nome text,
  atualizado_em timestamptz not null default now(),
  -- a pendencia: NOK corrigido depois do check
  corrigido_em timestamptz,
  corrigido_por_nome text,
  correcao text check (correcao is null or char_length(correcao) <= 500),
  constraint cf_respostas_item_unico unique (check_id, item_id)
);

create index if not exists cf_respostas_check_idx on public.cf_respostas (check_id);

-- Fotos no bucket privado "manutencao", pasta frota-check/.
create table if not exists public.cf_fotos (
  id uuid primary key default gen_random_uuid(),
  check_id uuid not null references public.cf_checks(id) on delete cascade,
  item_id uuid references public.cf_itens(id) on delete set null,
  revenda_id uuid not null references public.revendas(id) on delete cascade,
  tipo text not null default 'nok' check (tipo in ('nok', 'correcao')),
  caminho text not null,
  -- o id que o celular deu a foto: reenvio nao duplica
  chave text,
  bytes integer,
  enviada_por_nome text,
  criado_em timestamptz not null default now()
);

create index if not exists cf_fotos_check_idx on public.cf_fotos (check_id);
create unique index if not exists cf_fotos_chave_unica on public.cf_fotos (check_id, chave) where chave is not null;

