drop policy if exists "le cf_itens" on public.cf_itens;
create policy "le cf_itens" on public.cf_itens for select to authenticated using (true);
drop policy if exists "le cf_defeitos" on public.cf_defeitos;
create policy "le cf_defeitos" on public.cf_defeitos for select to authenticated using (true);

do $$
declare t text;
begin
  foreach t in array array['cf_veiculos', 'cf_checks', 'cf_respostas', 'cf_fotos']
  loop
    execute format('drop policy if exists "le %I da revenda" on public.%I', t, t);
    execute format(
      'create policy "le %I da revenda" on public.%I for select to authenticated
         using (public.ehowner_atual() or revenda_id in (select public.revendas_do_usuario()))',
      t, t
    );
  end loop;
end $$;

